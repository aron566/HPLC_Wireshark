b = bytes(int(x, 16) for x in hexline.split())
print("总长:", len(b))

# MSDU_BASE 头尾 12B = SourceMAC(01 44 64 51 85 14)+DestMAC(ff*6)
mac_tail = bytes([0x01,0x44,0x64,0x51,0x85,0x14,0xff,0xff,0xff,0xff,0xff,0xff])
E = b.find(mac_tail) + 12   # 头 28B 结束 = MSDU 体起点
print("MAC 尾结束(体起点) idx =", E)

# MSDULen=41:MSDU_Body = b[E:E+41];CRC = b[E+41:E+45]
body = b[E:E+41]
crc4 = b[E+41:E+45]
print("体41B:", body.hex(" "))
print("CRC4B :", crc4.hex(" "))

# Python cal_crc32 同款
def cal_crc32(data, length):
    CRCReg = 0xffffffff
    CRCPoly = 0xedb88320
    for i in range(0, length - 4):
        for j in range(0, 8):
            reg_tmp = ((data[i] >> j) & 0x1) ^ (CRCReg & 0x1)
            if reg_tmp == 0:
                CRCReg >>= 1
            else:
                CRCReg = (CRCReg >> 1) ^ CRCPoly
    return (~CRCReg) & 0xffffffff

rcv = crc4[0] | (crc4[1]<<8) | (crc4[2]<<16) | (crc4[3]<<24)
calc = cal_crc32(body, 41 + 4)   # Python 传 MSDULen+4 → 遍历 41B
print(f"rcv =0x{rcv:08x}  calc(41B)=0x{calc:08x}  match={rcv==calc}")

